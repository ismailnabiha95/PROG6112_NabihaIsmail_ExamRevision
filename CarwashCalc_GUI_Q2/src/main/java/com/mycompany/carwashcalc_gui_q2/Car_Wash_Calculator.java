    private void ClearForm()
{
    txtName.setText("");                          // empty the name field
    txtQuantity.setText("");                      // empty the quantity field
    cmbVehicle.setSelectedIndex(0);            // first item in the list is position...?
    chkMember.setSelected(false);                  // un-tick the check box: true or false?
    txtSubtotal.setText("");                      // clear the four results
    txtDiscount.setText("");
    txtVAT.setText("");
    txtTotal.setText("");
}
   
    private void ProcessCalculation()
{
    // ---------- 1. read the input ----------
    String name = txtName.getText();                          // customer name as text
    String vehicleType = cmbVehicle.getSelectedItem().toString();  // selected combo box item as text
    boolean isMember = chkMember.isSelected();                // true when the box is ticked
    int quantity;                                             // declared outside the try so it can be used later

    // ---------- 2. convert the quantity (try / catch) ----------
    try
    {
        quantity = Integer.parseInt(txtQuantity.getText());   // crashes here if the text is not a whole number
    }
    catch (NumberFormatException ex)                          // runs only when the conversion fails
    {
        JOptionPane.showMessageDialog(this, "Please enter a whole number for the quantity.");
        return;                                               // stop, do not calculate
    }

        ValidateData validator = new ValidateData();              // object for the validation class

    if (!validator.IsValid(name, quantity))                   // blank filled: the converted whole number
    {
        JOptionPane.showMessageDialog(this, "Name must not be empty and quantity must be above zero.");
        return;                                               // stop, do not calculate
    }

    // ---------- 4. calculate (only reached when the input is valid) ----------
    // delete the line "CarWash wash = new CarWash();" here: you already have it as a class-level field

    double price = wash.GetPrice(vehicleType);                // GetPrice needs the vehicle type text
    double subtotal = wash.CalculateSubtotal(price, quantity);                // price times the number of vehicles
    double discount = wash.CalculateDiscount(subtotal, quantity, isMember);   // isMember holds the check box tick
    double vat = wash.CalculateVat(subtotal - discount);      // VAT on the amount after the discount
    double total = wash.CalculateTotal(subtotal, discount);   // total due including VAT

    // ---------- 5. display ----------
    txtSubtotal.setText(String.format("R%.2f", subtotal));    // for example R360.00
    txtDiscount.setText(String.format("R%.2f", discount));        // for example R36.00
    txtVAT.setText(String.format("R%.2f", vat));              // for example R48.60
    txtTotal.setText(String.format("R%.2f", total));           // for example R372.60
}
    

