    private void Process() 
    {
    String movie = cmbMovie.getSelectedItem().toString();
    int tickets;                                              // declared before the try so they can be used after it
    double price;
    
    try
    {
        tickets = Integer.parseInt(txtTickets.getText());     // whole number of tickets
        price = Double.parseDouble(txtPrice.getText());              // price may have decimals: which method?
    }
    catch (NumberFormatException ex)
    {
        JOptionPane.showMessageDialog(this, "Tickets and price must be numbers.");   // message for bad numbers
        return;                                               // stop, do not continue
    }

    // ---------- 2. store the values in the data object ----------
    MovieTicketData data = new MovieTicketData();             // create the data object
    data.setMovieName(movie);                                 // setters store the values
    data.setNumberOfTickets(tickets);
    data.setTicketPrice(price);                                // which variable holds the price?

    // ---------- 3. validate ----------
    MovieTickets movieTickets = new MovieTickets();           // object for the logic class

    if (!movieTickets.ValidateData(data))                     // pass the data object
    {
        JOptionPane.showMessageDialog(this, "Please enter valid data: tickets and price must be above zero.");
        return;                                               // stop, do not calculate
    }

    // ---------- 4. calculate the total (includes the 14% VAT) ----------
    double total = movieTickets.CalculateTotalTicketPrice(data.getNumberOfTickets(), data.getTicketPrice());   // which getter gives the price?

    // ---------- 5. build the report text ----------
    String report = "MOVIE NAME: " + data.getMovieName() + "\n"
                  + "MOVIE TICKET PRICE: R " + data.getTicketPrice() + "\n"
                  + "NUMBER OF TICKETS: " + data.getNumberOfTickets() + "\n"
                  + "TOTAL TICKET PRICE: R " + total + "\n";   // which variable holds the total?

    txtReport.setText(report);                                // show it in the read-only text area

    // ---------- 6. save the report to report.txt ----------
    try (FileWriter writer = new FileWriter("report.txt"))          // the file name the paper uses
    {
        writer.write("MOVIE TICKET REPORT\n");                // title line, as in the sample file
        writer.write("***********************************\n");   // stars line
        writer.write(report);                                 // the four report lines
        writer.write("***********************************\n");   // closing stars line
    }
    catch (IOException ex)
    {
        JOptionPane.showMessageDialog(this, "Could not save the report.");   // message if saving fails
    }
    }
    
