package com.mycompany.q2gui_wagecalculator;


public class StaffMember {
    private String name;                          // private: only the getters and setters touch these
    private double hours;                         // hours worked
    private double rate;                          // hourly rate

    public StaffMember() 
    {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public double getHours() {
        return hours;
    }

    public void setHours(double hours) {
        this.hours = hours;
    }

    public double getRate() {
        return rate;
    }

    public void setRate(double rate) {
        this.rate = rate;
    }

    
    
}
