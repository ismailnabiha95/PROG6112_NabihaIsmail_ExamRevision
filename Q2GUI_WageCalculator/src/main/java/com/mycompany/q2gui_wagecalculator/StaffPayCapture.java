    private void AddRecord()
{
    // ---------- 1. the five-record limit ----------
    if (recordCount >= MAX_RECORDS)                // use the constant, not the number 5
    {
        JOptionPane.showMessageDialog(this, "Only 5 records are allowed.");   // message for a sixth record
        return;                                   // stop, do not add it
    }

    // ---------- 2. read and convert the input ----------
    String name = txtName.getText();         // staff name as text
    double hours;                                 // declared before the try so they can be used after it
    double rate;

    try
    {
        hours = Double.parseDouble(txtHours.getText());   // convert the hours
        rate = Double.parseDouble(txtRate.getText());            // convert the rate: which method?
    }
    catch (NumberFormatException ex)
    {
        JOptionPane.showMessageDialog(this, "Hours and rate must be numbers.");   // message for bad numbers
        return;                                   // stop
    }

    // ---------- 3. validate the rules ----------
    if (name.trim().isEmpty())                    // name must not be empty
    {
        JOptionPane.showMessageDialog(this, "Please enter a name.");
        return;
    }

    if (hours < 0 || hours > 80)                // outside 0 to 80: which operator means OR?
    {
        JOptionPane.showMessageDialog(this, "Hours must be between 0 and 80.");
        return;
    }

    if (rate <= 0)                                // rate must be above zero
    {
        JOptionPane.showMessageDialog(this, "Rate must be above zero.");
        return;
    }

    // ---------- 4. store the values in a StaffMember object ----------
    StaffMember staff = new StaffMember();        // create the data object
    staff.setName(name);                          // setters store the values
    staff.setHours(hours);
    staff.setRate(rate);                          // which variable holds the rate?

    // ---------- 5. calculate the pay ----------
    double pay = calculator.CalculatePay(staff.getHours(), staff.getRate());   // which getter gives the rate?

    // ---------- 6. show the record in the text area ----------
    txtRecords.append(staff.getName() + " - " + staff.getHours() + " hours - R" + String.format("%.2f", pay) + "\n");

    // ---------- 7. keep the line for the file ----------
    fileText = fileText + staff.getName() + "," + staff.getHours() + "," + staff.getRate() + "," + String.format("%.2f", pay) + "\n";

    // ---------- 8. update the totals ----------
    recordCount = recordCount + 1;             // one more record: add what?
    totalPay = totalPay + pay;                    // add this pay to the running total
    UpdateLabels();                               // refresh the two read-only fields
}
    
    private void UpdateLabels()
{
    txtCount.setText("" + recordCount);           // number of records captured
    txtTotalPay.setText(String.format("R%.2f", totalPay));   // which variable is the total?
}
        private void ClearForm()
    {
        txtName.setText("");                      // empty the name field
        txtHours.setText("");                     // empty the hours field
        txtRate.setText("");                      // empty the rate field
        txtRecords.setText("");                   // empty the records text area
        txtCount.setText("");                     // clear the count
        txtTotalPay.setText("");                  // clear the total pay
        recordCount = 0;                          // back to no records, so the limit is free again
        totalPay = 0;                             // the running total starts again
        fileText = "";                            // the file lines start again
    }
    
    private void SaveRecords()
{
    if (recordCount == 0)                      // nothing captured yet: which number?
    {
        JOptionPane.showMessageDialog(this, "There are no records to save.");   // message
        return;                                   // stop, do not write an empty file
    }

    try (FileWriter writer = new FileWriter("staff.txt"))   // the file name the paper uses
    {
        writer.write(fileText);                       // which variable holds all the lines?
    }
    catch (IOException ex)
    {
        JOptionPane.showMessageDialog(this, "Could not save the file.");   // message if saving fails
    }
}
    
    private void LoadRecords()
{
    txtRecords.setText("");                       // start with an empty text area
    recordCount = 0;                              // reset the counters before loading
    totalPay = 0;
    fileText = "";

    try (BufferedReader reader = new BufferedReader(new FileReader("staff.txt")))
    {
        String line = reader.readLine();          // read the first line

        while (line != null)                      // until there are no more lines
        {
            String[] parts = line.split(",");      // split the line at the commas

            // display format: name - hours - pay (parts[0], parts[1] and parts[3])
            txtRecords.append(parts[0] + " - " + parts[1] + " hours - R" + parts[3] + "\n");   // which position is the pay?

            fileText = fileText + line + "\n";    // keep the line so Save still works after a Load
            recordCount = recordCount + 1;        // count the record
            totalPay = totalPay + Double.parseDouble(parts[3]);   // add the pay to the total

            line = reader.readLine();             // read the next line
        }
    }
    catch (IOException ex)
    {
        JOptionPane.showMessageDialog(this, "Could not read the file.");   // message if reading fails
    }

    UpdateLabels();                               // refresh the count and total pay fields
}
