    private void SubmitTrip()
{
    // ===== Read the three combo boxes =====
    String start = cmbStart.getSelectedItem().toString();     // start location
    String end = cmbEnd.getSelectedItem().toString();         // end location
    String travel = cmbTravel.getSelectedItem().toString();   // travel by

    // ===== Q3.5: same location is an error =====
    if (start.equals(end))
    {
        JOptionPane.showMessageDialog(this, "Destinations cannot be the same!!");
        return;   // stop, nothing is saved
    }

    // ===== Q3.2: save one line (true = append) =====
    try (FileWriter writer = new FileWriter("travel.txt", true))
    {
        writer.write(start + "," + end + "," + travel + "\n");
    }
    catch (IOException ex)
    {
        JOptionPane.showMessageDialog(this, "Could not save the trip.");
    }

    LoadTravel();   // reload so the new trip shows
}
    private void LoadTravel()
{
    // ===== Title and star line first =====
    String log = "TRAVEL LOG\n" + "**********************************\n";

    // ===== Q3.3: read travel.txt line by line =====
    try (BufferedReader reader = new BufferedReader(new FileReader("travel.txt")))
    {
        String line;                                       // one line of the file
        while ((line = reader.readLine()) != null)         // null means end of file
        {
            String[] parts = line.split(",");              // cut at the commas
            log = log + "Destination 1: " + parts[0] + "\n"
                      + "Destination 2: " + parts[1] + "\n"
                      + "Travel By: " + parts[2] + "\n"
                      + "**********************************\n";
        }
    }
    catch (IOException ex)   // the file doesn't exist on the first run
    {
        log = log + "No trips saved yet.\n";
    }

    txtLog.setText(log);   // show it in the text area
}
