    String report = "";
    SurfSales s = new SurfSales();
    
    
    private void LoadData()
    {
    report = "Total Sales: " + s.GetTotalSales()+ "\n"           // \n starts the next line
                  + "Average Sales: " + Math.round(s.GetAverageSales()) + "\n"
                  + "Sales over target: " + s.GetSalesOverTarget()+ "\n"
                  + "Sales under target: " +s.GetSalesUnderTarget();
    
   lblYears.setText("Years Processed: " + s.GetYearsProcessed());
                
    txtReport.setText(report);                                 // read-only text area   
    }
    
    private void SaveData()
    {
     if (report.equals(""))                                    // nothing processed yet
    {
        JOptionPane.showMessageDialog(this, "load data first.");
        return;                                                   // stop: do not create an empty file
    }

    try (FileWriter writer = new FileWriter("sales_log.txt"))        // the file name the paper uses
    {
        writer.write("Sales Log\n");                    // title line, as in the sample file
        writer.write("***********************************\n");   // stars line
        writer.write(report + "\n");                          // the five report lines, plus a new line
        writer.write("***********************************\n");   // closing stars line
    }
    catch (IOException ex)
    {
        JOptionPane.showMessageDialog(this, "Could not save the report.");
    }
    }
    
    private void ClearForm()
{ report = "";
    
    txtReport.setText("");    // empty the report
    lblYears.setText("");
    
}

