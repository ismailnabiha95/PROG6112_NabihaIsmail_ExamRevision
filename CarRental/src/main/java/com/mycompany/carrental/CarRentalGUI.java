    // Process logic, shared by the menu item
private void processRental() {
    try {
        // 1. read the inputs (text fields give Strings, so parse them)
        String car = cmbCar.getSelectedItem().toString();
        int days = Integer.parseInt(txtDays.getText());
        double rate = Double.parseDouble(txtRate.getText());

        // 2. fill the data object
        CarRentalData data = new CarRentalData();
        data.setCarName(car);
        data.setNumberOfDays(days);
        data.setDailyRate(rate);

        // 3. validate, stop if invalid
        if (!rental.ValidateData(data)) {
            JOptionPane.showMessageDialog(this, "Please enter valid data.");
            return;
        }

        // 4. calculate the total (includes 15% VAT)
        double total = rental.CalculateTotalRentalPrice(days, rate);

        // 5. build the report and display it
        String report = "CAR NAME: " + car + "\n"
                      + "DAILY RATE: R " + rate + "\n"
                      + "NUMBER OF DAYS: " + days + "\n"
                      + "TOTAL RENTAL PRICE: R " + total;
        txtReport.setText(report);

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Days and rate must be numbers.");
    }
}

private void saveRental() {
    // do nothing useful if nothing has been processed yet
    if (txtReport.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please process the rental first.");
        return;
    }
    try (FileWriter writer = new FileWriter("rental.txt")) {
        writer.write("CAR RENTAL REPORT\n");
        writer.write("************************************\n");
        writer.write(txtReport.getText() + "\n");
        writer.write("************************************\n");
        // display success message
        JOptionPane.showMessageDialog(this, "Data saved successfully");
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "The file could not be saved.");
    }
}

