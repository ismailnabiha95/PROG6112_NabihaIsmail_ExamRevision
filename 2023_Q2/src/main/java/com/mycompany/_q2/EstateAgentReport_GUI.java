    private void ClearForm()
{ report = "";
    cmbLocation.setSelectedIndex(0);                  // back to the first item
    txtName.setText("");                        // empty the text fields
    txtPrice.setText("");
    txtpercent.setText("");
    txtReport.setText("");                         // empty the report
    
}
    
    private void ProcessReport()
{
     String Location = cmbLocation.getSelectedItem().toString();      // combo box item as text
     String name = txtName.getText();
     double price;
     double percent;
     
    try
    {
        price = Double.parseDouble(txtPrice.getText());      // decimals allowed
        percent=Double.parseDouble(txtpercent.getText());
              
    }
    catch (NumberFormatException ex)                           // text was not a number
    {
        JOptionPane.showMessageDialog(this, "Price and percentage must be numbers.");
        return;                                                // stop: never calculate with bad input
    }
    
    Data d = new  Data();
    d.setPrice(price);
    d.setCommission(percent);
    d.setName(name);
    d.setLocation(Location);
    
    EstateAgent agent = new EstateAgent();
    if (!agent.ValidateData(d))
    {
    {
        JOptionPane.showMessageDialog(this, "Please enter valid data.");
        return;                                                // stop
    }
    }
    
    // 3. calculate and show the report
    
    report = "Agent Location: " + d.getLocation()+ "\n"           // \n starts the next line
                  + "Agent Name: " + d.getName()+ "\n"
                  + "Property Price: " + d.getPrice()+ "\n"
                  + "Commission Percentage: " +d.getCommission() + "%\n"
                  + "Calculated commission: " + agent.CalculateCommission(txtPrice.getText(), txtpercent.getText());
    txtReport.setText(report);                                 // read-only text area   
}
    
    String report = "";
    
    private void SaveReport()
{
    if (report.equals(""))                                    // nothing processed yet
    {
        JOptionPane.showMessageDialog(this, "Process a report first.");
        return;                                                   // stop: do not create an empty file
    }

    try (FileWriter writer = new FileWriter("report.txt"))        // the file name the paper uses
    {
        writer.write("ESTATE AGENT REPORT\n");                    // title line, as in the sample file
        writer.write("***********************************\n");   // stars line
        writer.write(report + "\n");                          // the five report lines, plus a new line
        writer.write("***********************************\n");   // closing stars line
    }
    catch (IOException ex)
    {
        JOptionPane.showMessageDialog(this, "Could not save the report.");
    }
}
    

