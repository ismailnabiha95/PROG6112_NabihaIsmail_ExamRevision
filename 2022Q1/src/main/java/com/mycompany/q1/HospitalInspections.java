    private void SaveInspection()
{
    // ===== Check if the arrays are full =====
    if (count >=5)
    {
        JOptionPane.showMessageDialog(this, "Maximum inspection count reached!");
        return;   // stop here, don't save
    }

    // ===== Save the three values at position count =====
    names[count] = txtName.getText();            // read the text
    locations[count] = txtLocation.getText();
    years[count] = cmbYears.getSelectedIndex() + 1;   // "1 Year" is index 0

    count++;   // move to the next free spot

    // ===== Clear the inputs ready for the next one =====
    txtName.setText("");
    txtLocation.setText("");
    cmbYears.setSelectedIndex(0);
}
    
    private void PrintInspections()
{
    // ===== Check there is something to print =====
    if (count == 0)
    {
        JOptionPane.showMessageDialog(this, "No inspections saved yet!");
        return;   // nothing to print
    }

    

    // ===== Loop only to count, NOT to 5 (empty spots are null) =====
    for (int i = 0; i <count ; i++)
    {report = "";   // start empty each time
        report += "Hospital Name: " + names[i] + "\n";           // name
        report += "Hospital Location: " + locations[i] + "\n";   // location
        report += "Years Since Inspection: " + years[i] + " years\n";   // years
        report += "********************************\n";           // 32 stars
    }

    txtReport.setText(report);   // show it in the text area
}
    
