    private void loadProductData()
{
    // Call the methods from the ProductSales class
    int total = ps.GetTotalSales();
    double average = ps.GetAverageSales();
    int over = ps.GetSalesOverLimit();
    int under = ps.GetSalesUnderLimit();
    int years = ps.GetProductsProcessed();

    // Build the report one line at a time
    String report = "";
    report += "Total Sales: " + total + "\n";
    report += "Average Sales: " + Math.round(average) + "\n";   // rounds 366.666... to 367
    report += "Sales over limit: " + over + "\n";
    report += "Sales under limit: " + under + "\n";

    // Show the report, and the number of years, on the form
    txtData.setText(report);
    lblYears.setText("Years Processed: " + years);
}

private void saveProductData()
{
    String report = txtData.getText();

    // nothing to save yet
    if (report.trim().isEmpty())
    {
        JOptionPane.showMessageDialog(this, "Please load the product data first.");
        return;
    }

    try (FileWriter writer = new FileWriter("data.txt"))
    {
        // write report heading
        writer.write("Data log\n");
        // write separator line
        writer.write("**********************************\n");
        // write the text displayed in the text area
        writer.write(report);
        // write closing separator
        writer.write("\n**********************************\n");
        // display success message
        JOptionPane.showMessageDialog(this, "Data saved successfully");
    }
    catch (IOException ex)
    {
        // runs if the file cannot be written, and tells the user
        JOptionPane.showMessageDialog(this, "Error saving file: " + ex.getMessage());
    }
}
    


